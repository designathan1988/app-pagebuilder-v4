// Writes src/generated/ from the manifest and the English catalogue (npm run gen, checked by gen:check):
// - ids.ts: every id the code names, as a readonly array and its union type (CommandId, DoorId, PropertyId,
//   ElementType, MessageId…), so a wrong id is a type error;
// - commands.ts: the arguments of each command, typed from its manifest args;
// - value-lists.ts: the keywords and units each "generated" list offers (src/manifest/check.ts generatedOffer
//   and generatedUnits over css-properties.json and css-compat.json), so the editor never ships the 6.7 MB
//   compat data and never re-lists a value.
// The files hold data and types only.
import fs from 'node:fs';
import path from 'node:path';
import { excludedUnitsOf, generatedOffer, generatedUnits, type OfferData } from '../../src/manifest/check.ts';
import { loadManifest } from '../manifest/load.ts';
import {
  checksFileSchema,
  commandsFileSchema,
  elementsFileSchema,
  environmentSchema,
  featuresFileSchema,
  exclusionsFileSchema,
  generatedCompatSchema,
  generatedCssSchema,
  interactionsFileSchema,
  layoutFileSchema,
  propertiesFileSchema,
  referencesFileSchema,
  type Command,
} from '../../src/manifest/schema.ts';

export const TYPES_DIR = 'src/generated';

const HEADER = '// Generated by `npm run gen` (tools/gen/types.ts) from manifest/ and src/i18n/locales/en.json. Do not edit:\n// change the manifest or the generator and run npm run gen. gen:check fails when this file is stale or edited.\n';

const q = (s: string) => JSON.stringify(s);
const union = (values: readonly string[]) => (values.length === 0 ? 'never' : values.map(q).join(' | '));

// `export const NAME_IDS = [...] as const; export type Name = (typeof NAME_IDS)[number];`
function idList(constName: string, typeName: string, ids: readonly string[], doc: string): string {
  const unique = [...new Set(ids)];
  const lines = unique.map((id) => `  ${q(id)},`).join('\n');
  return `// ${doc}\nexport const ${constName} = [\n${lines}\n] as const;\nexport type ${typeName} = (typeof ${constName})[number];\n`;
}

function argType(arg: Command['args'][string]): string {
  switch (arg.type) {
    case 'node':
      return 'NodeId';
    case 'nodes':
      return 'readonly NodeId[]';
    case 'string':
    case 'path':
    case 'file':
    case 'color':
      return 'string';
    case 'files':
      return 'readonly PickedFile[]';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'enum':
      return arg.values.length === 0 ? 'string' : union(arg.values);
    case 'json':
      return 'JsonValue';
    case 'palette-entry':
      return 'PaletteEntryId';
    case 'property':
      return 'StyleTargetId';
    case 'attribute':
      return 'AttributeId';
    // a project's own breakpoints are the document's (core/document/breakpoints.ts): any id, read at run time
    case 'breakpoint':
      return 'string';
    case 'state':
      return 'StateId';
    case 'point':
      return 'Point';
    case 'rect':
      return 'Rect';
    case 'clipboard':
      return 'ClipboardContent';
  }
}

function generateTypes(root: string): { file: string; content: string }[] {
  // the manifest as tools/manifest/load.ts reads it for manifest:check: one reader of the files
  const { input } = loadManifest(root);
  const file = (name: string) => input.files[name];
  const sorted = (dir: string, only: RegExp = /./) => Object.keys(input.files).filter((f) => f.startsWith(`${dir}/`) && only.test(f)).sort();
  const commandFiles = sorted('commands').map((f) => commandsFileSchema.parse(file(f)));
  const commands = commandFiles.flatMap((f) => f.commands);
  // the feature groups only: features/fixtures/ holds the scenarios' project documents
  const featureFiles = sorted('features', /^features\/\d{2}-[a-z0-9-]+\.json$/).map((f) => featuresFileSchema.parse(file(f)));
  const properties = propertiesFileSchema.parse(file('properties.json'));
  const elements = elementsFileSchema.parse(file('elements.json'));
  const interactions = interactionsFileSchema.parse(file('interactions.json'));
  const layout = layoutFileSchema.parse(file('layout.json'));
  const checks = checksFileSchema.parse(file('checks.json'));
  const environment = environmentSchema.parse(file('environment.json'));
  const references = referencesFileSchema.parse(file('references.json'));
  const en = input.catalogues.en as Record<string, string>;
  const referenced = (kind: string) => references.references.filter((r) => r.kind === kind).map((r) => r.id).sort();

  const ids = [
    HEADER,
    idList('COMMAND_IDS', 'CommandId', commands.map((c) => c.id), 'every command of manifest/commands/*.json, in file order'),
    idList('DOOR_IDS', 'DoorId', commands.flatMap((c) => c.entryPoints.map((d) => `${c.id}#${d.id}`)), 'every door, as "<command>#<door>"'),
    idList('PROPERTY_IDS', 'PropertyId', properties.properties.map((p) => p.id), 'every edited CSS property (properties.json properties)'),
    idList('COMPOSITE_IDS', 'CompositeId', properties.composites.map((c) => c.id), 'every composite (properties.json composites)'),
    idList('RECIPE_IDS', 'RecipeId', properties.recipes.map((r) => r.id), 'every compatibility recipe (properties.json recipes)'),
    '// what a door edits: a property, a composite or a recipe\nexport type StyleTargetId = PropertyId | CompositeId | RecipeId;\n',
    idList('SECTION_IDS', 'SectionId', properties.sections.map((s) => s.id), 'the inspector sections, in order'),
    idList('BREAKPOINT_IDS', 'BreakpointId', properties.breakpoints.map((b) => b.id), 'the breakpoints in cascade order, the base first'),
    idList('STATE_IDS', 'StateId', properties.states.map((s) => s.id), 'the style states'),
    idList('ELEMENT_TYPES', 'ElementType', elements.elements.map((e) => e.id), 'every element type (elements.json elements)'),
    idList('ATTRIBUTE_IDS', 'AttributeId', elements.attributes.map((a) => a.id), 'every attribute field (elements.json attributes)'),
    idList('PALETTE_GROUP_IDS', 'PaletteGroupId', elements.palette.map((g) => g.id), 'the palette groups'),
    idList('PALETTE_ENTRY_IDS', 'PaletteEntryId', elements.palette.flatMap((g) => g.entries.map((e) => e.id)), 'the palette entries'),
    idList('FEATURE_IDS', 'FeatureId', featureFiles.flatMap((f) => f.features.map((x) => x.id)), 'every feature, in build order'),
    idList('REGION_IDS', 'RegionId', layout.regions.map((r) => r.id), 'the regions of manifest/layout.json'),
    idList('MENU_IDS', 'MenuId', layout.menus.map((m) => m.id), 'the menus (layout.json)'),
    idList('KEY_CONTEXT_IDS', 'KeyContextId', interactions.keyContexts.map((k) => k.id), 'the key contexts (interactions.json)'),
    idList('CONSTANT_IDS', 'ConstantId', interactions.constants.map((c) => c.id), 'the interaction constants (interactions.json)'),
    idList('GESTURE_IDS', 'GestureId', interactions.gestures.map((g) => g.id), 'the pointer gestures (interactions.json)'),
    idList('CHECK_CATEGORY_IDS', 'CheckCategoryId', checks.categories.map((c) => c.id), 'the categories of the Checks tab'),
    idList('LOCALES', 'Locale', environment.locales.available, 'the UI languages (environment.json)'),
    `// the UI language of a fresh profile (environment.json)\nexport const DEFAULT_LOCALE: Locale = ${q(environment.locales.default)};\n`,
    idList('PREDICATE_IDS', 'PredicateId', referenced('predicate'), 'the predicates the manifest names (references.json)'),
    idList('CODEC_IDS', 'CodecId', referenced('codec'), 'the codecs the manifest names (references.json)'),
    idList('ACTION_IDS', 'ActionId', referenced('action'), 'the coupling actions the manifest names (references.json)'),
    idList('MESSAGE_IDS', 'MessageId', Object.keys(en), 'every key of the English catalogue, the source catalogue'),
  ].join('\n');

  const args = commands
    .map((c) => {
      const fields = Object.entries(c.args).map(([name, arg]) => `readonly ${name}${arg.optional ? '?' : ''}: ${argType(arg)}`);
      return `  ${q(c.id)}: ${fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`};`;
    })
    .join('\n');
  const commandTypes = `${HEADER}import type { AttributeId, CommandId, FeatureId, MessageId, PaletteEntryId, StateId, StyleTargetId } from './ids.ts';

export type NodeId = string;
export type JsonValue = string | number | boolean | null | readonly JsonValue[] | { readonly [key: string]: JsonValue };
export interface Point {
  readonly x: number;
  readonly y: number;
}
export interface Rect {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}
// what the system clipboard held when a door read it (an argument of type "clipboard"): its HTML as a tree of texts and
// elements (each element's tag, its href when it has one, its children), its plain text and its HTML as the markup it
// was (which the HTML importer reads, spec clipboard-paste-external), each null when absent; or the browser's refusal
// to let the editor read it
export type ClipboardNode = string | { readonly tag: string; readonly href: string | null; readonly children: readonly ClipboardNode[] };
export type ClipboardContent =
  | { readonly status: 'read'; readonly html: readonly ClipboardNode[] | null; readonly text: string | null; readonly markup?: string | null }
  | { readonly status: 'denied' };
// what a door that reads several files hands the command (an argument of type "files", File › Import HTML): each
// picked file — its name (the path it has inside an archive it came from), its MIME type, its bytes as base64 and,
// for an image, its intrinsic size; the door expands an archive into its entries, and one it cannot read stands for
// its own file with the reason instead (src/core/import/import.ts readPickedFiles): one of the archive reader's
// reasons, as a message (src/core/project/zip.ts), or an error's text
export interface PickedFile {
  readonly name: string;
  readonly type: string;
  readonly bytes: string;
  readonly width?: number;
  readonly height?: number;
  readonly error?: string | { readonly key: MessageId; readonly params: Readonly<Record<string, string | number>> };
}

// the arguments of each command (manifest/commands/*.json args)
export interface CommandArgs {
${args}
}

// every command has its arguments declared
export type CommandArgsOf<Id extends CommandId> = CommandArgs[Id];

// the commands each feature lists (manifest/features/*.json), for the doors whose feature is data of their own
export const FEATURE_COMMANDS: Readonly<Record<FeatureId, readonly CommandId[]>> = {
${featureFiles.flatMap((f) => f.features.map((x) => `  ${q(x.id)}: ${JSON.stringify(x.commands)},`)).join('\n')}
};
`;

  const data: OfferData = {
    properties,
    css: generatedCssSchema.parse(file('generated/css-properties.json')),
    compat: generatedCompatSchema.parse(file('generated/css-compat.json')),
    excludedUnits: excludedUnitsOf(exclusionsFileSchema.parse(file('css-exclusions.json'))),
  };
  const byDoor = commands.flatMap((c) => c.entryPoints.flatMap((d) => (d.adapter.offers?.list === 'generated' ? [d.adapter.offers.property] : [])));
  // and the longhands of every composite offered that way: a codec tells which longhand a word of the composite names
  // by their lists (border-top: its width, style and colour)
  const longhandsOffered = properties.composites.filter((c) => byDoor.includes(c.id)).flatMap((c) => c.longhands);
  const offered = [...new Set([...byDoor, ...longhandsOffered])].sort();
  const lists = offered
    .map((id) => `  ${q(id)}: { keywords: ${JSON.stringify(generatedOffer(data, id) ?? [])}, units: ${JSON.stringify(generatedUnits(data, id) ?? [])} },`)
    .join('\n');
  // a recipe that is a CSS property of its own (line-clamp) has its initial value too: a field of it shows it while the
  // element holds none (the user's review of 2026-10-05: Line clamp was an empty field)
  const initials = [...properties.properties, ...properties.recipes]
    .flatMap((p) => {
      const css = data.css.properties[p.id];
      return css !== undefined && !css.inherited && typeof css.initial === 'string' ? [`  ${q(p.id)}: ${q(css.initial)},`] : [];
    })
    .join('\n');
  const inheritedIds = properties.properties.filter((p) => data.css.properties[p.id]?.inherited === true).map((p) => `  ${q(p.id)},`);
  const valueLists = `${HEADER}import type { StyleTargetId } from './ids.ts';

export interface GeneratedValues {
  readonly keywords: readonly string[];
  readonly units: readonly string[];
}

// The keywords and units a door's "generated" list offers, for every property, composite or recipe a door offers
// that way: those of its official syntax (css-properties.json) that Chrome, Firefox and Safari all support
// (css-compat.json). A declared subset or preset list is read from properties.json.
export const GENERATED_VALUES: Readonly<Partial<Record<StyleTargetId, GeneratedValues>>> = {
${lists}
};

// The initial value of every edited property that is not inherited (css-properties.json), and of a recipe that is a CSS
// property of its own: what an element holds for it while it holds none of its own, as a coupling's condition reads it
// (src/core/style/couplings.ts) and a field shows it when the page computes nothing for it (line-clamp in Chrome).
export const INITIAL_VALUES: Readonly<Partial<Record<string, string>>> = {
${initials}
};

// Every edited property that is inherited (css-properties.json): an element holding none of its own takes its parent's,
// as the Style tab says where a value comes from (src/editor/inspector/origin.ts).
export const INHERITED_PROPERTIES: ReadonlySet<string> = new Set([
${inheritedIds.join('\n')}
]);
`;
  return [
    { file: `${TYPES_DIR}/ids.ts`, content: ids },
    { file: `${TYPES_DIR}/commands.ts`, content: commandTypes },
    { file: `${TYPES_DIR}/value-lists.ts`, content: valueLists },
  ];
}

export function writeTypes(root: string): string[] {
  fs.mkdirSync(path.join(root, TYPES_DIR), { recursive: true });
  return generateTypes(root).map(({ file, content }) => {
    fs.writeFileSync(path.join(root, file), content);
    return file;
  });
}
