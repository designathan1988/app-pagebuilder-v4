// The editor's one icon library is Lucide (lucide-static, ISC license; archive/DESIGN.md "Icons"). npm run gen writes:
// - manifest/generated/icons.json: the name of every icon of the installed Lucide, which manifest:check rule
//   icon-name checks every icon the manifest names against;
// - src/ui/icons.svg: a sprite with one <symbol id="<name>"> for each icon the manifest names (door icons, menu
//   anchors, the layout's glyphs, element icons, keyword icons), drawn from Lucide's icon nodes. The shell draws
//   icons only from this sprite, by the names the manifest gives.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { loadManifest } from '../manifest/load.ts';
import { packageVersion } from './versions.ts';

const require = createRequire(import.meta.url);

export const ICONS_FILE = 'icons.json';
export const ICON_SPRITE = 'src/ui/icons.svg';

type IconNode = [string, Record<string, string | number>][];

function lucideNodes(): Record<string, IconNode> {
  const file = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icon-nodes.json');
  return JSON.parse(fs.readFileSync(file, 'utf8')) as Record<string, IconNode>;
}

export function generateIconNames(): Record<string, unknown> {
  return {
    $generated: {
      notice: 'Generated by `npm run gen` (tools/gen/icons.ts) from the package named in "from". Do not edit: change the package version and run npm run gen.',
      by: 'tools/gen/icons.ts',
      from: { 'lucide-static': packageVersion('lucide-static') },
    },
    icons: Object.keys(lucideNodes()).sort(),
  };
}

// Every icon name the hand-written manifest gives.
function namedIcons(root: string): string[] {
  const { files } = loadManifest(root).input;
  const names = new Set<string>();
  const add = (name: unknown) => {
    if (typeof name === 'string') names.add(name);
  };
  for (const [file, json] of Object.entries(files)) {
    if (!file.startsWith('commands/')) continue;
    for (const command of (json as { commands: { entryPoints: { icon?: unknown }[] }[] }).commands) for (const door of command.entryPoints) add(door.icon);
  }
  const layout = files['layout.json'] as { menus: { anchors: { icon?: unknown }[] }[]; glyphs?: Record<string, unknown>; panels?: Record<string, { icon?: unknown }> };
  for (const menu of layout.menus) for (const anchor of menu.anchors) add(anchor.icon);
  for (const glyph of Object.values(layout.glyphs ?? {})) add(glyph);
  for (const panel of Object.values(layout.panels ?? {})) add(panel.icon);
  for (const element of (files['elements.json'] as { elements: { icon: unknown }[] }).elements) add(element.icon);
  for (const group of (files['elements.json'] as { palette: { entries: { icon?: unknown }[] }[] }).palette) for (const entry of group.entries) add(entry.icon);
  for (const property of (files['properties.json'] as { properties: { icons?: Record<string, unknown> }[] }).properties) for (const icon of Object.values(property.icons ?? {})) add(icon);
  return [...names].sort();
}

const attribute = (name: string, value: string | number) => `${name}="${String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;')}"`;

export function generateSprite(root: string): string {
  const nodes = lucideNodes();
  const symbols = namedIcons(root).map((name) => {
    const node = nodes[name];
    // an unknown name is reported by manifest:check rule icon-name; the sprite leaves it out
    if (!node) return null;
    const children = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => attribute(k, v)).join(' ')}/>`).join('');
    return `  <symbol id="${name}" viewBox="0 0 24 24">${children}</symbol>`;
  });
  // the licence travels with the copy: ISC, and MIT for the icons derived from Feather, require their notices in copies
  const licence = fs
    .readFileSync(path.join(path.dirname(require.resolve('lucide-static/package.json')), 'LICENSE'), 'utf8')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .trim();
  return [
    `<!-- Generated by \`npm run gen\` (tools/gen/icons.ts): the icons the manifest names, from lucide-static ${packageVersion('lucide-static')} (https://lucide.dev); its licence is in <metadata>. Do not edit. -->`,
    '<svg xmlns="http://www.w3.org/2000/svg">',
    `  <metadata>${licence}</metadata>`,
    ...symbols.filter((s): s is string => s !== null),
    '</svg>',
    '',
  ].join('\n');
}
